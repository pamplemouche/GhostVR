#!/usr/bin/env python3
"""Turn `data/vault_catalogue.json` into the store module the worker imports.

The Oculus Store asks the backend two questions (see
`com/oculus/horizon/api/ApiDispatcher.smali`):

  node(<category>) { all_items... { nodes { ...latest_supported_binary { uri } } } }
  app_binary_update(app_id: <id>) { new_binary { uri, size, obb_binary { uri } } }

so every catalogue entry needs a stable id and a download URI before the store
can render or install anything. Both are derived from the vault APK filename,
which is the package name.

The output is a JS module rather than JSON so wrangler bundles it without a
loader flag, and so the description text can be trimmed at build time - the
whole file has to stay well under the worker's size limit.

Usage:
    python3 tools/build_store_payload.py
    python3 tools/build_store_payload.py --apk-base https://cdn.example.com/apk
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = ROOT / "data" / "vault_catalogue.json"
OUT = ROOT / "src" / "store_data.js"

# The store renders `display_long_description` in a scrollable panel, so a long
# description is fine on screen but wasteful in the bundle. The vault blurbs are
# review notes anyway; keep enough to be useful and cut the rest.
MAX_DESCRIPTION = 320

# Item ids have to survive a round trip through `node(<id>)` and
# `app_binary_update(app_id: <id>)`. The `gv:` prefix keeps our ids from
# colliding with anything Meta-shaped, and the package name is already unique.
ID_PREFIX = "gv:"


def section_of(entry: dict) -> str:
    """Bucket an app into a store section. The vault has no genre field."""
    text = f"{entry['display_name']} {entry['description']}".lower()
    if re.search(r"\bdemo\b|\btrial\b", text):
        return "demos"
    if re.search(r"\bvideo\b|\bmovie\b|\b360\b|\bcinema\b", text):
        return "video"
    if re.search(r"\bexperience\b|\bshort\b|\bstory\b|\bjourney\b", text):
        return "experiences"
    return "games"


SECTIONS = [
    ("games", "Games"),
    ("experiences", "Experiences"),
    ("video", "Video"),
    ("demos", "Demos"),
]


def clean(text: str, limit: int) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    if len(text) <= limit:
        return text
    # Cut on a word boundary so the panel does not end mid-word.
    return text[:limit].rsplit(" ", 1)[0] + "..."


def build(catalogue: dict, apk_base: str) -> dict:
    items: dict[str, dict] = {}
    buckets: dict[str, list[str]] = {key: [] for key, _ in SECTIONS}

    for package, entry in sorted(catalogue.items()):
        item_id = f"{ID_PREFIX}{package}"
        section = section_of(entry)
        items[item_id] = {
            "id": item_id,
            "package_name": package,
            "display_name": entry["display_name"] or package,
            "display_short_description": clean(entry["description"], 140),
            "display_long_description": clean(entry["description"], MAX_DESCRIPTION),
            "developer_name": "",
            "category_name": section,
            "apk": entry["apk"],
        }
        buckets[section].append(item_id)

    base = apk_base.rstrip("/")
    return {
        "apk_base": base,
        "sections": [
            {"id": key, "name": name, "item_ids": buckets[key]}
            for key, name in SECTIONS
            if buckets[key]
        ],
        "items": items,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalogue", type=Path, default=CATALOGUE)
    parser.add_argument("--out", type=Path, default=OUT)
    # Empty base means "hand out the vault URL": the binaries are 100 MB each
    # and 865 of them do not fit in git, so the vault stays the origin until a
    # mirror is stood up and passed here.
    parser.add_argument("--apk-base", default="", help="our own APK mirror, if any")
    args = parser.parse_args()

    catalogue = json.loads(args.catalogue.read_text(encoding="utf-8"))
    data = build(catalogue, args.apk_base)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "// Generated by tools/build_store_payload.py - do not edit by hand.\n"
        "// Source: data/vault_catalogue.json (vault.gearvr.net)\n"
        f"export const STORE = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    size = args.out.stat().st_size
    print(f"{len(data['items'])} items, {len(data['sections'])} sections -> {args.out.name} ({size / 1024:.0f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
